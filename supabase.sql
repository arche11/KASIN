-- Jalankan sekali di Supabase Dashboard > SQL Editor > New query.
create table if not exists public.transactions (
  id bigint generated by default as identity primary key,
  kind text not null check (kind in ('masuk', 'keluar')),
  description text not null,
  person text not null default '',
  amount bigint not null check (amount > 0),
  category text not null,
  happened_on date not null,
  created_at timestamptz not null default now()
);

-- Aplikasi mengakses tabel melalui backend menggunakan secret/service-role key.
-- Jangan berikan akses baca/tulis anonim pada tabel buku kas.
alter table public.transactions enable row level security;
grant all on table public.transactions to service_role;
grant usage, select on sequence public.transactions_id_seq to service_role;
